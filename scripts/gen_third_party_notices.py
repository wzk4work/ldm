def run(args: list[str]) -> str:
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def shipped_ids() -> set[tuple[str, str]]:
    args = ["cargo", "tree", "--locked", "-e", "normal,build", "--target", TARGET, "--prefix", "none", "-f", "{p}"]
    for p in SHIPPED:
        args += ["-p", p]
    out = set()
    for line in run(args).splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[1].startswith("v"):
            out.add((parts[0], parts[1][1:]))
    return out


def main() -> int:
    meta = json.loads(run(["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", TARGET]))
    members = set(meta["workspace_members"])
    want = shipped_ids()
    pkgs = sorted(
        (p for p in meta["packages"] if (p["name"], p["version"]) in want and p["id"] not in members),
        key=lambda p: (p["name"].lower(), p["version"]),
    )
    texts: dict[str, str] = {}
    groups: dict[str, list[str]] = {}
    lines = [f"{len(pkgs)} crates. Identical license texts are printed once (4.2) and referenced by tag.", "", "4.1 Crate list", ""]
    for p in pkgs:
        d = Path(p["manifest_path"]).parent
        files = sorted(f for f in d.iterdir() if f.is_file() and f.name.lower().startswith(LICENSE_PREFIXES))
        tags = []
        for f in files:
            t = f.read_text(errors="replace").strip()
            tag = "T" + hashlib.sha256(t.encode()).hexdigest()[:8]
            texts.setdefault(tag, t)
            groups.setdefault(tag, []).append(f"{p['name']} {p['version']} ({f.name})")
            tags.append(tag)
        repo = p.get("repository") or p.get("homepage") or ""
        lic = p.get("license") or "see license file"
        ref = ", ".join(tags) if tags else "no license file in the crate; standard text of the SPDX license applies"
        lines.append(f"- {p['name']} {p['version']}  [{lic}]  {repo}".rstrip())
        lines.append(f"    texts: {ref}")
    lines += ["", "4.2 License texts", ""]
    for tag in sorted(texts, key=lambda t: (groups[t][0].lower(), t)):
        lines += ["=" * 78, f"[{tag}] used by: " + "; ".join(groups[tag]), "-" * 78, texts[tag], ""]
    body = HEADER + "\n" + "\n".join(lines).rstrip() + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != body:
            print("THIRD_PARTY_NOTICES is out of date: run scripts/gen_third_party_notices.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(body)
    print(f"wrote {OUT.name}: {len(pkgs)} crates, {len(texts)} distinct license texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
